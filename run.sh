#!/usr/bin/env bash
set -Eeuo pipefail

# Project-WARP-Unlock SmartDNS version
# Features:
# - Download latest wgcf automatically
# - amd64 / arm64 auto-detect
# - SmartDNS instead of dnsmasq
# - Selectable stack mode:
#     1) dual  -> IPv4 + IPv6 policy routing
#     2) ipv4  -> IPv4 only policy routing
#     3) ipv6  -> IPv6 only policy routing
#     4) none  -> only generate WireGuard config, no PostUp/PreDown hooks
# - Uses numeric routing table 250 for Debian 12 / Debian 13 compatibility
# - In IPv6-enabled modes, adds high-metric IPv6 default route for: curl -6 --interface wg ...

WG_IF="${WG_IF:-wg}"
WG_DIR="/etc/wireguard"
WG_CONF="${WG_DIR}/${WG_IF}.conf"
WGCF_BIN="${WG_DIR}/wgcf"
WGCF_ACCOUNT="${WG_DIR}/wgcf-account.toml"
WGCF_VERSION="${WGCF_VERSION:-latest}"

ROUTE_TABLE_ID="${ROUTE_TABLE_ID:-250}"
MARK="${MARK:-2}"

# dual / ipv4 / ipv6 / none
STACK_MODE="${STACK_MODE:-__ASK__}"

# By default, keep the Endpoint generated by wgcf.
# You can override it when running:
# WARP_ENDPOINT=162.159.193.1:2408 ./run.sh
WARP_ENDPOINT="${WARP_ENDPOINT:-}"

SMARTDNS_CONF="/etc/smartdns/smartdns.conf"

log() {
  echo -e "\033[1;32m[Info]\033[0m $*"
}

warn() {
  echo -e "\033[1;33m[Warn]\033[0m $*"
}

err() {
  echo -e "\033[1;31m[Error]\033[0m $*" >&2
}

require_root() {
  if [ "${EUID}" -ne 0 ]; then
    err "Please run as root."
    exit 1
  fi
}

select_stack_mode() {
  # If STACK_MODE was explicitly provided by environment, accept it after validation.
  # Otherwise show an interactive menu.
  if [ -n "${STACK_MODE:-}" ] && [ "${STACK_MODE}" != "__ASK__" ]; then
    case "${STACK_MODE}" in
      dual|ipv4|ipv6|none)
        log "Selected stack mode from environment: ${STACK_MODE}"
        return 0
        ;;
      *)
        warn "Invalid STACK_MODE from environment: ${STACK_MODE}"
        ;;
    esac
  fi

  echo
  echo "请选择 WARP 分流模式："
  echo "  1) 双栈 IPv4 + IPv6 分流，推荐"
  echo "  2) 只启用 IPv4 分流"
  echo "  3) 只启用 IPv6 分流"
  echo "  4) 不添加分流 hook，只生成普通 WireGuard 配置"
  echo

  local choice
  while true; do
    read -r -p "请输入选项 [1-4]，默认 1: " choice
    choice="${choice:-1}"

    case "${choice}" in
      1)
        STACK_MODE="dual"
        break
        ;;
      2)
        STACK_MODE="ipv4"
        break
        ;;
      3)
        STACK_MODE="ipv6"
        break
        ;;
      4)
        STACK_MODE="none"
        break
        ;;
      *)
        echo "无效选项，请输入 1、2、3 或 4。"
        ;;
    esac
  done

  log "Selected stack mode: ${STACK_MODE}"
}

want_ipv4() {
  [ "${STACK_MODE}" = "dual" ] || [ "${STACK_MODE}" = "ipv4" ]
}

want_ipv6() {
  [ "${STACK_MODE}" = "dual" ] || [ "${STACK_MODE}" = "ipv6" ]
}

want_hooks() {
  [ "${STACK_MODE}" != "none" ]
}

detect_arch() {
  local arch
  arch="$(uname -m)"

  case "${arch}" in
    x86_64|amd64)
      WGCF_ARCH="amd64"
      SMARTDNS_ARCHES=("x86_64" "amd64")
      ;;
    aarch64|arm64)
      WGCF_ARCH="arm64"
      SMARTDNS_ARCHES=("aarch64" "arm64")
      ;;
    *)
      err "Unsupported architecture: ${arch}. Only amd64 and arm64 are supported."
      exit 1
      ;;
  esac

  log "Detected architecture: ${arch}, wgcf arch: ${WGCF_ARCH}"
}

apt_install_base() {
  log "Installing base dependencies..."

  export DEBIAN_FRONTEND=noninteractive

  apt-get update
  apt-get install -y \
    ca-certificates \
    curl \
    wget \
    tar \
    gzip \
    wireguard \
    wireguard-tools \
    dnsutils \
    mtr \
    lsof \
    procps \
    sed \
    gawk \
    grep

  if want_hooks; then
    apt-get install -y ipset iptables
  fi

  mkdir -p "${WG_DIR}"
}

install_smartdns() {
  if command -v smartdns >/dev/null 2>&1; then
    log "SmartDNS already installed: $(smartdns -v 2>&1 | head -n 1 || true)"
    return 0
  fi

  log "Trying to install SmartDNS from apt..."

  if apt-get install -y smartdns >/dev/null 2>&1; then
    log "SmartDNS installed from apt."
    return 0
  fi

  warn "apt install smartdns failed. Trying SmartDNS GitHub release package..."

  local api url tmp file arch_pattern
  api="https://api.github.com/repos/pymumu/smartdns/releases/latest"
  tmp="$(mktemp -d)"
  url=""

  for arch_pattern in "${SMARTDNS_ARCHES[@]}"; do
    url="$(curl -fsSL "${api}" \
      | grep -E '"browser_download_url":' \
      | sed -E 's/.*"browser_download_url": *"([^"]+)".*/\1/' \
      | grep -Ei "${arch_pattern}.*(linux-all\.tar\.gz|debian-all\.deb)$" \
      | head -n 1 || true)"

    if [ -n "${url}" ]; then
      break
    fi
  done

  if [ -z "${url}" ]; then
    err "Cannot find SmartDNS package for this architecture."
    err "Please install SmartDNS manually, then rerun this script."
    exit 1
  fi

  log "Downloading SmartDNS package: ${url}"

  file="${tmp}/smartdns.pkg"
  curl -fL "${url}" -o "${file}"

  if echo "${url}" | grep -q '\.deb$'; then
    dpkg -i "${file}" || apt-get -f install -y
  elif echo "${url}" | grep -q '\.tar\.gz$'; then
    tar -zxf "${file}" -C "${tmp}"
    local install_script
    install_script="$(find "${tmp}" -type f -name install | head -n 1 || true)"

    if [ -z "${install_script}" ]; then
      err "SmartDNS install script not found in package."
      exit 1
    fi

    chmod +x "${install_script}"
    cd "$(dirname "${install_script}")"
    ./install -i
  else
    err "Unknown SmartDNS package format: ${url}"
    exit 1
  fi

  rm -rf "${tmp}"

  if ! command -v smartdns >/dev/null 2>&1; then
    err "SmartDNS installation failed."
    exit 1
  fi

  log "SmartDNS installed: $(smartdns -v 2>&1 | head -n 1 || true)"
}

disable_dnsmasq_and_resolved() {
  log "Disabling dnsmasq and systemd-resolved if present..."

  systemctl disable --now dnsmasq >/dev/null 2>&1 || true
  systemctl stop dnsmasq >/dev/null 2>&1 || true

  systemctl disable --now systemd-resolved >/dev/null 2>&1 || true
  systemctl stop systemd-resolved >/dev/null 2>&1 || true

  if [ -L /etc/resolv.conf ]; then
    rm -f /etc/resolv.conf
  else
    cp -a /etc/resolv.conf "/etc/resolv.conf.backup.$(date +%Y%m%d_%H%M%S)" 2>/dev/null || true
  fi

  cat > /etc/resolv.conf <<'EOF'
nameserver 127.0.0.1
nameserver 1.1.1.1
nameserver 8.8.8.8
EOF
}

install_wgcf() {
  log "Installing wgcf..."

  local version url

  if [ "${WGCF_VERSION}" = "latest" ]; then
    version="$(curl -fsSL https://api.github.com/repos/ViRb3/wgcf/releases/latest \
      | grep -E '"tag_name":' \
      | sed -E 's/.*"tag_name": *"v?([^"]+)".*/\1/' \
      | head -n 1)"
  else
    version="${WGCF_VERSION#v}"
  fi

  if [ -z "${version}" ]; then
    err "Failed to detect wgcf latest version."
    exit 1
  fi

  url="https://github.com/ViRb3/wgcf/releases/download/v${version}/wgcf_${version}_linux_${WGCF_ARCH}"

  log "Downloading wgcf v${version} for linux_${WGCF_ARCH}: ${url}"

  curl -fL "${url}" -o "${WGCF_BIN}"
  chmod +x "${WGCF_BIN}"

  log "wgcf installed: $("${WGCF_BIN}" --version 2>/dev/null || echo "v${version}")"
}

filter_wireguard_addresses() {
  local input="$1"
  local output="$2"

  case "${STACK_MODE}" in
    dual)
      cp "${input}" "${output}"
      ;;
    ipv4)
      # Keep only IPv4 Address lines.
      awk '
        /^Address *=/ {
          if ($0 ~ /[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+/) print
          next
        }
        { print }
      ' "${input}" > "${output}"
      ;;
    ipv6)
      # Keep only IPv6 Address lines.
      awk '
        /^Address *=/ {
          if ($0 ~ /:/) print
          next
        }
        { print }
      ' "${input}" > "${output}"
      ;;
    none)
      # Keep original dual-stack wgcf profile in plain mode.
      cp "${input}" "${output}"
      ;;
  esac
}

generate_warp_profile() {
  log "Generating WARP WireGuard profile..."

  mkdir -p "${WG_DIR}"
  cd "${WG_DIR}"

  if [ ! -f "${WGCF_ACCOUNT}" ]; then
    "${WGCF_BIN}" register --accept-tos --config "${WGCF_ACCOUNT}"
  else
    log "Existing wgcf account found: ${WGCF_ACCOUNT}"
  fi

  "${WGCF_BIN}" generate --config "${WGCF_ACCOUNT}" --profile "${WG_CONF}.raw"

  log "Normalizing WireGuard profile..."

  local filtered_profile
  filtered_profile="${WG_CONF}.filtered"
  filter_wireguard_addresses "${WG_CONF}.raw" "${filtered_profile}"

  if want_hooks; then
    awk '
      /^\[Interface\]/ {
        print
        print "Table = off"
        print "PostUp = /etc/wireguard/up"
        print "PreDown = /etc/wireguard/down"
        next
      }

      /^Table *=/ { next }
      /^PostUp *=/ { next }
      /^PreDown *=/ { next }
      /^PostDown *=/ { next }
      /^PreUp *=/ { next }
      /^DNS *=/ { next }
      /^PersistentKeepalive *=/ { next }

      {
        print
      }

      END {
        print "PersistentKeepalive = 5"
      }
    ' "${filtered_profile}" > "${WG_CONF}"
  else
    awk '
      /^Table *=/ { next }
      /^PostUp *=/ { next }
      /^PreDown *=/ { next }
      /^PostDown *=/ { next }
      /^PreUp *=/ { next }
      /^DNS *=/ { next }
      /^PersistentKeepalive *=/ { next }

      {
        print
      }

      END {
        print "PersistentKeepalive = 5"
      }
    ' "${filtered_profile}" > "${WG_CONF}"
  fi

  if [ -n "${WARP_ENDPOINT}" ]; then
    log "Overriding WireGuard Endpoint: ${WARP_ENDPOINT}"
    sed -i -E "s#^Endpoint *=.*#Endpoint = ${WARP_ENDPOINT}#g" "${WG_CONF}"
  else
    log "Keeping default wgcf Endpoint."
  fi

  chmod 600 "${WG_CONF}"

  log "WireGuard profile written to ${WG_CONF}"
}

