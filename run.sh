write_wireguard_hooks() {
  if ! want_hooks; then
    log "STACK_MODE=none: skipping WireGuard hook scripts."
    rm -f /etc/wireguard/up /etc/wireguard/down
    return 0
  fi

  log "Writing WireGuard hook scripts..."

  cat > /etc/wireguard/up <<EOF
#!/usr/bin/env bash
set -e

WG_IF="${WG_IF}"
TABLE_ID="${ROUTE_TABLE_ID}"
MARK="${MARK}"
STACK_MODE="${STACK_MODE}"

want_ipv4() {
  [ "\${STACK_MODE}" = "dual" ] || [ "\${STACK_MODE}" = "ipv4" ]
}

want_ipv6() {
  [ "\${STACK_MODE}" = "dual" ] || [ "\${STACK_MODE}" = "ipv6" ]
}

if want_ipv4; then
  ipset create warp hash:ip family inet -exist

  iptables -t mangle -N fwmark 2>/dev/null || true
  iptables -t mangle -C PREROUTING -j fwmark 2>/dev/null || iptables -t mangle -A PREROUTING -j fwmark
  iptables -t mangle -C OUTPUT -j fwmark 2>/dev/null || iptables -t mangle -A OUTPUT -j fwmark
  iptables -t mangle -C fwmark -m set --match-set warp dst -j MARK --set-mark "\$MARK" 2>/dev/null || \\
  iptables -t mangle -A fwmark -m set --match-set warp dst -j MARK --set-mark "\$MARK"

  ip rule add fwmark "\$MARK" table "\$TABLE_ID" 2>/dev/null || true
  ip route replace default dev "\$WG_IF" table "\$TABLE_ID"

  iptables -t nat -C POSTROUTING -m mark --mark "\$MARK" -j MASQUERADE 2>/dev/null || \\
  iptables -t nat -A POSTROUTING -m mark --mark "\$MARK" -j MASQUERADE

  iptables -t mangle -C POSTROUTING -o "\$WG_IF" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu 2>/dev/null || \\
  iptables -t mangle -A POSTROUTING -o "\$WG_IF" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu
fi

if want_ipv6; then
  ipset create warp6 hash:ip family inet6 -exist

  ip6tables -t mangle -N fwmark6 2>/dev/null || true
  ip6tables -t mangle -C PREROUTING -j fwmark6 2>/dev/null || ip6tables -t mangle -A PREROUTING -j fwmark6
  ip6tables -t mangle -C OUTPUT -j fwmark6 2>/dev/null || ip6tables -t mangle -A OUTPUT -j fwmark6
  ip6tables -t mangle -C fwmark6 -m set --match-set warp6 dst -j MARK --set-mark "\$MARK" 2>/dev/null || \\
  ip6tables -t mangle -A fwmark6 -m set --match-set warp6 dst -j MARK --set-mark "\$MARK"

  ip -6 rule add fwmark "\$MARK" table "\$TABLE_ID" 2>/dev/null || true
  ip -6 route replace default dev "\$WG_IF" table "\$TABLE_ID"

  # High-metric IPv6 default route for manual tests:
  # curl -6 --interface wg https://ip.sb
  # Native IPv6 default route should still win if it has lower metric.
  ip -6 route replace default dev "\$WG_IF" metric 4096

  ip6tables -t nat -C POSTROUTING -m mark --mark "\$MARK" -j MASQUERADE 2>/dev/null || \\
  ip6tables -t nat -A POSTROUTING -m mark --mark "\$MARK" -j MASQUERADE

  ip6tables -t mangle -C POSTROUTING -o "\$WG_IF" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu 2>/dev/null || \\
  ip6tables -t mangle -A POSTROUTING -o "\$WG_IF" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu
fi
EOF

  cat > /etc/wireguard/down <<EOF
#!/usr/bin/env bash

WG_IF="${WG_IF}"
TABLE_ID="${ROUTE_TABLE_ID}"
MARK="${MARK}"
STACK_MODE="${STACK_MODE}"

want_ipv4() {
  [ "\${STACK_MODE}" = "dual" ] || [ "\${STACK_MODE}" = "ipv4" ]
}

want_ipv6() {
  [ "\${STACK_MODE}" = "dual" ] || [ "\${STACK_MODE}" = "ipv6" ]
}

if want_ipv4; then
  iptables -t mangle -D PREROUTING -j fwmark 2>/dev/null || true
  iptables -t mangle -D OUTPUT -j fwmark 2>/dev/null || true
  iptables -t mangle -D fwmark -m set --match-set warp dst -j MARK --set-mark "\$MARK" 2>/dev/null || true
  iptables -t mangle -D POSTROUTING -o "\$WG_IF" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu 2>/dev/null || true
  iptables -t mangle -F fwmark 2>/dev/null || true
  iptables -t mangle -X fwmark 2>/dev/null || true

  iptables -t nat -D POSTROUTING -m mark --mark "\$MARK" -j MASQUERADE 2>/dev/null || true

  ip rule del fwmark "\$MARK" table "\$TABLE_ID" 2>/dev/null || true
  ip route flush table "\$TABLE_ID" 2>/dev/null || true

  ipset destroy warp 2>/dev/null || true
fi

if want_ipv6; then
  ip6tables -t mangle -D PREROUTING -j fwmark6 2>/dev/null || true
  ip6tables -t mangle -D OUTPUT -j fwmark6 2>/dev/null || true
  ip6tables -t mangle -D fwmark6 -m set --match-set warp6 dst -j MARK --set-mark "\$MARK" 2>/dev/null || true
  ip6tables -t mangle -D POSTROUTING -o "\$WG_IF" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu 2>/dev/null || true
  ip6tables -t mangle -F fwmark6 2>/dev/null || true
  ip6tables -t mangle -X fwmark6 2>/dev/null || true

  ip6tables -t nat -D POSTROUTING -m mark --mark "\$MARK" -j MASQUERADE 2>/dev/null || true

  ip -6 rule del fwmark "\$MARK" table "\$TABLE_ID" 2>/dev/null || true
  ip -6 route flush table "\$TABLE_ID" 2>/dev/null || true
  ip -6 route del default dev "\$WG_IF" metric 4096 2>/dev/null || true

  ipset destroy warp6 2>/dev/null || true
fi
EOF

  chmod +x /etc/wireguard/up /etc/wireguard/down
}

configure_sysctl() {
  if ! want_hooks; then
    log "STACK_MODE=none: skipping sysctl forwarding config."
    return 0
  fi

  log "Configuring sysctl forwarding..."

  {
    if want_ipv4; then
      echo "net.ipv4.ip_forward=1"
    fi

    if want_ipv6; then
      echo "net.ipv6.conf.all.forwarding=1"
      echo "net.ipv6.conf.default.forwarding=1"
    fi
  } > /etc/sysctl.d/99-warp-unlock.conf

  sysctl --system >/dev/null || true
}

enable_services() {
  log "Enabling services..."

  systemctl daemon-reload

  systemctl enable smartdns >/dev/null 2>&1 || true
  systemctl restart smartdns

  systemctl enable "wg-quick@${WG_IF}" >/dev/null 2>&1 || true
  systemctl restart "wg-quick@${WG_IF}"
}

run_checks() {
  log "Running checks..."

  echo
  echo "===== Mode ====="
  echo "STACK_MODE=${STACK_MODE}"

  echo
  echo "===== WireGuard config addresses ====="
  grep -E "^(Address|Table|PostUp|PreDown|Endpoint|AllowedIPs)" "${WG_CONF}" || true

  echo
  echo "===== WireGuard ====="
  wg show || true

  if want_ipv4; then
    echo
    echo "===== IPv4 policy routing ====="
    ip rule | grep "lookup ${ROUTE_TABLE_ID}" || true
    ip route show table "${ROUTE_TABLE_ID}" || true
  fi

  if want_ipv6; then
    echo
    echo "===== IPv6 policy routing ====="
    ip -6 rule | grep "lookup ${ROUTE_TABLE_ID}" || true
    ip -6 route show table "${ROUTE_TABLE_ID}" || true
    ip -6 route | grep "${WG_IF}" || true
  fi

  echo
  echo "===== SmartDNS test ====="
  dig @127.0.0.1 youtube.com A +short || true
  dig @127.0.0.1 youtube.com AAAA +short || true

  if want_ipv4; then
    echo
    echo "===== ipset warp ====="
    ipset list warp 2>/dev/null | sed -n '1,20p' || true
    echo
    echo "===== IPv4 mangle counters ====="
    iptables -t mangle -vnL fwmark 2>/dev/null || true
    echo
    echo "===== IPv4 curl test ====="
    curl -4 --connect-timeout 8 https://ipinfo.io --interface "${WG_IF}" || true
    echo
  fi

  if want_ipv6; then
    echo
    echo "===== ipset warp6 ====="
    ipset list warp6 2>/dev/null | sed -n '1,20p' || true
    echo
    echo "===== IPv6 mangle counters ====="
    ip6tables -t mangle -vnL fwmark6 2>/dev/null || true
    echo
    echo "===== IPv6 curl test ====="
    curl -6 --connect-timeout 8 https://ip.sb --interface "${WG_IF}" || true
    echo
  fi
}

